CREATE TABLE tasks (
  id TEXT PRIMARY KEY,
  satellite TEXT NOT NULL,
  plane TEXT NOT NULL,
  class TEXT NOT NULL,
  imaging_start TIMESTAMPTZ NOT NULL,
  imaging_end TIMESTAMPTZ NOT NULL,
  duration_s INTEGER NOT NULL CHECK (duration_s > 0),
  incidence DOUBLE PRECISION NOT NULL,
  look_side TEXT NOT NULL CHECK (look_side IN ('LEFT', 'RIGHT')),
  pass TEXT NOT NULL CHECK (pass IN ('ASCENDING', 'DESCENDING')),
  squint DOUBLE PRECISION NOT NULL,
  client_ref TEXT,
  created_at TIMESTAMPTZ NOT NULL,
  status TEXT NOT NULL,
  cancelled_at TIMESTAMPTZ,
  lat DOUBLE PRECISION NOT NULL,
  lon DOUBLE PRECISION NOT NULL,
  mode TEXT NOT NULL,
  requested_look TEXT NOT NULL,
  requested_pass TEXT NOT NULL,
  incidence_choice TEXT NOT NULL,
  window_start TIMESTAMPTZ NOT NULL,
  window_end TIMESTAMPTZ NOT NULL,
  CONSTRAINT tasks_imaging CHECK (imaging_end > imaging_start),
  CONSTRAINT tasks_client_ref UNIQUE (client_ref),
  CONSTRAINT tasks_status CHECK (status IN ('scheduled', 'imaging', 'downlink', 'processing', 'done', 'cancelled', 'failed')),
  CONSTRAINT tasks_lat CHECK (lat >= -90 AND lat <= 90),
  CONSTRAINT tasks_lon CHECK (lon >= -180 AND lon <= 180),
  CONSTRAINT tasks_requested_look CHECK (requested_look IN ('ANY', 'LEFT', 'RIGHT')),
  CONSTRAINT tasks_requested_pass CHECK (requested_pass IN ('ANY', 'ASCENDING', 'DESCENDING')),
  CONSTRAINT tasks_incidence_choice CHECK (incidence_choice IN ('performant', 'widest')),
  CONSTRAINT tasks_no_overlap EXCLUDE USING gist (
    satellite WITH =,
    tstzrange(imaging_start, imaging_end, '[)') WITH &&
  ) WHERE (status NOT IN ('cancelled', 'failed'))
);
