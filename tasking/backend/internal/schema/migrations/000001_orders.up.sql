CREATE TABLE orders (
  id TEXT PRIMARY KEY,
  task_id TEXT NOT NULL,
  status TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  cancelled_at TIMESTAMPTZ,
  satellite TEXT NOT NULL,
  plane TEXT NOT NULL,
  class TEXT NOT NULL,
  lat DOUBLE PRECISION NOT NULL,
  lon DOUBLE PRECISION NOT NULL,
  mode TEXT NOT NULL,
  requested_look TEXT NOT NULL,
  requested_pass TEXT NOT NULL,
  incidence_choice TEXT NOT NULL,
  window_start TIMESTAMPTZ NOT NULL,
  window_end TIMESTAMPTZ NOT NULL,
  imaging_start TIMESTAMPTZ NOT NULL,
  imaging_end TIMESTAMPTZ NOT NULL,
  duration_s INTEGER NOT NULL CHECK (duration_s > 0),
  incidence DOUBLE PRECISION NOT NULL CHECK (incidence >= 0 AND incidence <= 90),
  look_side TEXT NOT NULL,
  pass TEXT NOT NULL,
  squint DOUBLE PRECISION NOT NULL,
  CONSTRAINT orders_lat CHECK (lat >= -90 AND lat <= 90),
  CONSTRAINT orders_lon CHECK (lon >= -180 AND lon <= 180),
  CONSTRAINT orders_requested_look CHECK (requested_look IN ('ANY', 'LEFT', 'RIGHT')),
  CONSTRAINT orders_requested_pass CHECK (requested_pass IN ('ANY', 'ASCENDING', 'DESCENDING')),
  CONSTRAINT orders_incidence_choice CHECK (incidence_choice IN ('performant', 'widest')),
  CONSTRAINT orders_look_side CHECK (look_side IN ('LEFT', 'RIGHT')),
  CONSTRAINT orders_pass CHECK (pass IN ('ASCENDING', 'DESCENDING')),
  CONSTRAINT orders_window CHECK (window_end > window_start),
  CONSTRAINT orders_imaging CHECK (imaging_end > imaging_start),
  CONSTRAINT orders_imaging_inside_window CHECK (
    imaging_start >= window_start AND imaging_end <= window_end
  )
);
